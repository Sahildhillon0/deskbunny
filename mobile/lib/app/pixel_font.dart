/// [text] as the font can draw it: upper case, accents dropped to their base
/// letter, anything else removed. Runs of spaces collapse.
String fontSafe(String text) {
  final out = StringBuffer();
  for (final r in text.toUpperCase().runes) {
    var ch = String.fromCharCode(r);
    ch = _plain[ch] ?? ch;
    if (_glyphs.containsKey(ch)) out.write(ch);
  }
  return out.toString().replaceAll(RegExp(r' +'), ' ').trim();
}

/// Width in pixels of [text] at [scale] (one pixel gap between glyphs, none after the last).
int textWidth(String text, {int scale = 1}) => text.isEmpty ? 0 : text.length * (glyphW + 1) * scale - scale;

/// The longest prefix of [text] that fits in [maxWidth] pixels at [scale].
String fitText(String text, int maxWidth, {int scale = 1}) {
  var t = text;
  while (t.isNotEmpty && textWidth(t, scale: scale) > maxWidth) {
    t = t.substring(0, t.length - 1);
  }
  return t.trimRight();
}

/// [text] broken into at most [maxLines] lines no wider than [maxWidth] at
/// [scale]: at spaces where it can, inside a word that is too long. When text
/// is left over, the last line ends in "..". Pass [fontSafe] text.
List<String> wrapText(String text, int maxWidth, {int scale = 1, int maxLines = 2}) {
  final fit = (maxWidth + scale) ~/ ((glyphW + 1) * scale); // glyphs per line
  if (fit < 1 || text.isEmpty) return const [];
  final lines = <String>[];
  var rest = text;
  while (rest.isNotEmpty && lines.length < maxLines) {
    if (rest.length <= fit) {
      lines.add(rest);
      rest = '';
      break;
    }
    var cut = rest.lastIndexOf(' ', fit);
    if (cut <= 0) cut = fit; // one long word: break inside it
    lines.add(rest.substring(0, cut).trimRight());
    rest = rest.substring(cut).trimLeft();
  }
  if (rest.isNotEmpty && lines.isNotEmpty) {
    final last = lines.removeLast();
    final keep = last.length > fit - 2 ? last.substring(0, fit - 2) : last;
    lines.add('${keep.trimRight()}..');
  }
  return lines;
}

/// Draws [text] with its top-left at (x, y); returns the width drawn. [on]
/// false clears instead of lights. Characters the font lacks are skipped.
int drawText(Uint8List frame, String text, int x, int y, {int scale = 1, bool on = true}) {
  var cx = x;
  for (final ch in fontSafe(text).split('')) {
    final rows = _glyphs[ch]!;
    for (var r = 0; r < glyphH; r++) {
      for (var c = 0; c < glyphW; c++) {
        if (rows[r] & (1 << (glyphW - 1 - c)) == 0) continue;
        stamp(frame, cx + c * scale + (scale - 1) ~/ 2, y + r * scale + (scale - 1) ~/ 2, scale, on);
      }
    }
    cx += (glyphW + 1) * scale;
  }
  return cx - x - (cx > x ? scale : 0);
}
